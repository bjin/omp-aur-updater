import importlib.util
import tempfile
import unittest
from pathlib import Path


MODULE_PATH = Path(__file__).resolve().parents[1] / "scripts" / "update_grammar_release.py"
SPEC = importlib.util.spec_from_file_location("update_grammar_release", MODULE_PATH)
if SPEC is None or SPEC.loader is None:
    raise RuntimeError(f"Unable to load {MODULE_PATH}")
updater = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(updater)


def header(version: str) -> bytes:
    return (
        f"//! Generated by `bun run gen:grammars` from stencil-hq/wasm-grammars v{version}; do\n"
    ).encode()


class GrammarReleaseTests(unittest.TestCase):
    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.registry = Path(temporary.name) / "wasm_grammars.rs"
        self.pkgbuild = Path(temporary.name) / "PKGBUILD"

    def test_changed_pin_preserves_other_package_metadata(self) -> None:
        self.registry.write_bytes(header("2.10") + b"//! not edit.\n")
        original = (
            "pkgver=18.8.7\npkgrel=3\n_grammar_release='1'\n"
            'optdepends=("oh-my-pi-grammars-bin=${_grammar_release}: grammars")\n'
        )
        self.pkgbuild.write_text(original)
        self.assertEqual(
            ("2.10", True), updater.update_grammar_release(self.registry, self.pkgbuild)
        )
        self.assertEqual(
            original.replace("_grammar_release='1'", '_grammar_release="2.10"'),
            self.pkgbuild.read_text(),
        )

    def test_equal_version_does_not_change_quoting_or_emit_change(self) -> None:
        self.registry.write_bytes(header("1"))
        for pin in ("1", "'1'", '"1"'):
            with self.subTest(pin=pin):
                original = f"_grammar_release={pin}\n"
                self.pkgbuild.write_text(original)
                self.assertEqual(
                    ("1", False),
                    updater.update_grammar_release(self.registry, self.pkgbuild),
                )
                self.assertEqual(original, self.pkgbuild.read_text())

    def test_application_pin_tracks_older_required_registry(self) -> None:
        # The optional dependency follows the registry; only the grammar AUR
        # publication step rejects downgrades.
        self.registry.write_bytes(header("1"))
        self.pkgbuild.write_text("_grammar_release=2\n")
        self.assertEqual(
            ("1", True), updater.update_grammar_release(self.registry, self.pkgbuild)
        )
        self.assertEqual('_grammar_release="1"\n', self.pkgbuild.read_text())

    def test_header_must_match_entire_first_line(self) -> None:
        valid = header("2")
        invalid_headers = (
            b"",
            b"\n" + valid,
            b"// other generator\n" + valid,
            b" " + valid,
            valid.rstrip(b"\n") + b" not edit.\n",
            valid.replace(b"; do", b"; do "),
            valid.replace(b"\n", b"\r\n"),
            valid.replace(b"stencil-hq", b"other-owner"),
            header(""),
            header("2/3"),
            header("2-3"),
            header('2"; echo bad'),
        )
        original = b"_grammar_release=1\n"
        for content in invalid_headers:
            with self.subTest(content=content):
                self.registry.write_bytes(content)
                self.pkgbuild.write_bytes(original)
                with self.assertRaises(ValueError):
                    updater.update_grammar_release(self.registry, self.pkgbuild)
                self.assertEqual(original, self.pkgbuild.read_bytes())

    def test_missing_ambiguous_or_nonliteral_pin_fails_without_mutation(self) -> None:
        self.registry.write_bytes(header("2"))
        for original in (
            "pkgver=1\n",
            "_grammar_release=1\n_grammar_release=2\n",
            "_grammar_release=1\n_grammar_release=$other\n",
            "_grammar_release=${release}\n",
            "_grammar_release='1\"\n",
        ):
            with self.subTest(original=original):
                self.pkgbuild.write_text(original)
                with self.assertRaises(ValueError):
                    updater.update_grammar_release(self.registry, self.pkgbuild)
                self.assertEqual(original, self.pkgbuild.read_text())


if __name__ == "__main__":
    unittest.main()
