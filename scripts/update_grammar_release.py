#!/usr/bin/env python3
"""Synchronize an AUR grammar pin with the generated upstream registry."""

import argparse
import re
from pathlib import Path


# A release must also be usable as an Arch pkgver (no whitespace, slash, or dash).
VERSION = r"[0-9][0-9A-Za-z._+]*"
HEADER = re.compile(
    rf"//! Generated by `bun run gen:grammars` from stencil-hq/wasm-grammars v({VERSION}); do"
)
PIN = re.compile(rf"_grammar_release=([\"']?)({VERSION})\1")


def update_grammar_release(registry: Path, pkgbuild: Path) -> tuple[str, bool]:
    with registry.open("rb") as source:
        first_line = source.readline().removesuffix(b"\n").decode("utf-8")
    header = HEADER.fullmatch(first_line)
    if header is None:
        raise ValueError(f"Unexpected wasm_grammars.rs first line: {first_line!r}")
    version = header[1]

    text = pkgbuild.read_text(encoding="utf-8")
    pins = list(re.finditer(r"^_grammar_release=.*$", text, re.MULTILINE))
    if len(pins) != 1 or (value := PIN.fullmatch(pins[0][0])) is None:
        raise ValueError("Expected exactly one literal _grammar_release in PKGBUILD")
    pin = pins[0]
    changed = value[2] != version
    if changed:
        pkgbuild.write_text(
            text[: pin.start()] + f'_grammar_release="{version}"' + text[pin.end() :],
            encoding="utf-8",
        )
    return version, changed


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("registry", type=Path)
    parser.add_argument("pkgbuild", type=Path)
    args = parser.parse_args()
    try:
        version, changed = update_grammar_release(args.registry, args.pkgbuild)
    except ValueError as error:
        parser.exit(1, f"{error}\n")
    print(version, str(changed).lower())


if __name__ == "__main__":
    main()
